@Composable
fun DexReaderTheme(
  themeOption: ThemeModeValue = ThemeModeValue.DARK,
  content: @Composable () -> Unit,
) {
  val isDarkTheme = themeOption == ThemeModeValue.DARK

  MaterialTheme(
    colorScheme = if (isDarkTheme) darkScheme else lightScheme,
    shapes = Shapes,
    typography = Typography,
    content = content
  )
}